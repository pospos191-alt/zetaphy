#!/usr/bin/env python3
"""Writes audit-package/ERROR_CODES.md and audit-package/INSTRUCTIONS.md from
programs/swd_amm/src (the Anchor 0.31 IDL lists only one error enum, and the
instruction set depends on the feature set).

    python3 audit-package/tools/gen_tables.py          # write
    python3 audit-package/tools/gen_tables.py --check  # fail if stale
"""
import os
import re
import sys

ROOT = os.path.join(os.path.dirname(__file__), "..", "..")
SRC = os.path.join(ROOT, "programs", "swd_amm", "src")
OUT = os.path.join(ROOT, "audit-package")
GATE = '#[cfg(not(feature = "v2-only"))]'


def read(f):
    return open(os.path.join(SRC, f), encoding="utf-8").read()


def errors():
    rows = []
    for f in sorted(os.listdir(SRC)):
        if not f.endswith(".rs"):
            continue
        t = read(f)
        for m in re.finditer(r'#\[error_code(?:\(offset\s*=\s*(\d+)\))?\]\s*pub enum (\w+)\s*\{([\s\S]*?)\n\}', t):
            base = int(m.group(1) or 6000)
            msg = None
            n = 0
            for line in m.group(3).split("\n"):
                s = line.strip()
                mm = re.match(r'#\[msg\("(.*)"\)\]', s)
                if mm:
                    msg = mm.group(1); continue
                mv = re.match(r'(\w+),?$', s)
                if mv and not s.startswith("//"):
                    rows.append((base + n, m.group(2), mv.group(1), msg or "", f))
                    n += 1; msg = None
    return rows


def instructions():
    t = read("lib.rs")
    body = t[t.index("#[program]\npub mod"):]
    body = body[: body.index("\n}\n")]
    out, gated = [], False
    for line in body.split("\n"):
        s = line.strip()
        if s == GATE:
            gated = True; continue
        m = re.match(r'pub fn (\w+)\(\s*ctx:\s*Context<(\w+)>', s) or re.match(r'pub fn (\w+)\($', s)
        if m:
            out.append((m.group(1), not gated)); gated = False
    return out


def render():
    e = errors()
    v2_files = {"lib.rs", "governance.rs", "oracle.rs", "swdmm_v2.rs", "timelock.rs"}
    lines = ["# swd_amm error codes", "",
             "Generated by `audit-package/tools/gen_tables.py` from the `#[error_code]` enums. Anchor 0.31.1's IDL",
             "lists only one of these enums (and numbers it from 6000), so use this table, not the IDL, to decode",
             "`custom program error: 0x...` values. Codes are identical in the full and the `v2-only` build",
             "(`DlmmError` does not exist in `v2-only`).", "",
             "| Code | Hex | Enum | Variant | Message | File | In v2-only |", "|---|---|---|---|---|---|---|"]
    for code, en, v, msg, f in sorted(e):
        lines.append(f"| {code} | 0x{code:x} | {en} | {v} | {msg.replace('|', '/')} | `{f}` | {'yes' if f in v2_files else 'no'} |")
    ix = instructions()
    il = ["# swd_amm instructions", "",
          "Generated by `audit-package/tools/gen_tables.py` from the `#[program]` module in `lib.rs`.",
          f"Full build: {len(ix)} instructions. `v2-only` build (mainnet / audit scope): {sum(1 for _, k in ix if k)}.", "",
          "| # | Instruction | In v2-only (audit scope) |", "|---|---|---|"]
    for i, (n, keep) in enumerate(ix, 1):
        il.append(f"| {i} | `{n}` | {'yes' if keep else 'no (CP / DLMM)'} |")
    return {"ERROR_CODES.md": "\n".join(lines) + "\n", "INSTRUCTIONS.md": "\n".join(il) + "\n"}


def main():
    stale = []
    for name, text in render().items():
        p = os.path.join(OUT, name)
        if "--check" in sys.argv:
            if not os.path.exists(p) or open(p, encoding="utf-8").read() != text:
                stale.append(name)
        else:
            open(p, "w", encoding="utf-8").write(text)
    if stale:
        sys.exit("stale (run audit-package/tools/gen_tables.py): " + ", ".join(stale))


if __name__ == "__main__":
    main()
