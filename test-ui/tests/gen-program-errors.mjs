// Builds test-ui/program-errors.js from the program's Rust error enums
// (programs/swd_amm/src/*.rs, every #[error_code] block with its offset).
// Anchor's IDL lists only ONE of the six enums, so the page cannot rely on
// it for readable errors. Run after changing the program's errors:
//   node test-ui/tests/gen-program-errors.mjs          (writes the file)
//   node test-ui/tests/gen-program-errors.mjs --check  (CI: fails when stale)
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const src = path.resolve(here, "../../programs/swd_amm/src");
const out = path.resolve(here, "../program-errors.js");
const FILES = ["lib.rs", "dlmm.rs", "governance.rs", "oracle.rs", "swdmm_v2.rs", "timelock.rs"];

// Category -> the plain-language hint key in i18n.js (errCat*). First match wins.
const OVERRIDE = {
  InvalidPriceImpactCap: "input", EmergencyPauseRequestEmpty: "input", PositionNotEmpty: "input",
  NotActivated: "paused", SwapTooLarge: "slippage", MultisigVaultMismatch: "auth",
  NotASquadsMultisigAccount: "auth", MultisigAccountTooShort: "auth", EmergencyCannotEqualGovernance: "input",
  PriceConfidenceTooWide: "oracle", PriceVerificationNotFull: "oracle",
  TransferFeeMintNotSupported: "allow", UnsupportedMintExtension: "allow",
};
const CATS = [
  ["slippage", /Slippage|MinOut|MinAmount|PriceImpact|ImpactTooHigh|PriceLimit/i],
  ["paused", /Paused|NotStarted|NotActive|Activation/i],
  ["auth", /Unauthori[sz]ed|Authority|NotCreator|OnlyCreator|Signer|Owner/i],
  ["oracle", /Oracle|Price(Too)?Stale|PriceUnavailable|Deviation|Feed|Pyth/i],
  ["timelock", /Timelock|Pending|Action|Unpause/i],
  ["allow", /Allow|Policy|NotReviewed|Token2022|TokenProgram/i],
  ["liquidity", /Liquidity|Reserve|Shares|NoLiquidity|Insufficient|Empty|Locked/i],
  ["math", /Overflow|Underflow|Math|DivideByZero/i],
  ["input", /.*/],
];

function parse() {
  const errs = [];
  for (const f of FILES) {
    const text = fs.readFileSync(path.join(src, f), "utf8");
    for (const m of text.matchAll(/#\[error_code(?:\(offset\s*=\s*(\d+)\))?\]\s*pub enum (\w+)\s*\{([\s\S]*?)\n\}/g)) {
      let code = m[1] ? Number(m[1]) : 6000;
      for (const v of m[3].matchAll(/#\[msg\("((?:[^"\\]|\\.)*)"\)\]\s*(\w+)\s*,?/g)) {
        const name = v[2];
        const cat = OVERRIDE[name] || CATS.find(([, re]) => re.test(name))[0];
        errs.push({ code: code++, name, msg: v[1].replace(/\\"/g, '"'), enum: m[2], cat });
      }
    }
  }
  return errs.sort((a, b) => a.code - b.code);
}

const errs = parse();
const body = `// GENERATED by tests/gen-program-errors.mjs from programs/swd_amm/src — do not edit by hand.
// code -> [name, message from the program, category]; category -> i18n key errCat<Category>.
export const PROGRAM_ERRORS = {
${errs.map((e) => `  ${e.code}: ${JSON.stringify([e.name, e.msg, e.cat])},`).join("\n")}
};

const BY_NAME = Object.fromEntries(Object.entries(PROGRAM_ERRORS).map(([c, [n]]) => [n, Number(c)]));

/** Finds the program error in an error / log text: "custom program error: 0x1771", "Error Number: 6001", or "Error Code: Name". */
export function findProgramError(text) {
  const s = String(text || "");
  let code = null;
  const hex = s.match(/custom program error: 0x([0-9a-f]+)/i);
  if (hex) code = parseInt(hex[1], 16);
  const num = s.match(/Error Number: (\\d+)/);
  if (code == null && num) code = Number(num[1]);
  const nm = s.match(/Error Code: (\\w+)/);
  if (code == null && nm && BY_NAME[nm[1]] != null) code = BY_NAME[nm[1]];
  if (code == null || !PROGRAM_ERRORS[code]) return null;
  const [name, msg, cat] = PROGRAM_ERRORS[code];
  return { code, name, msg, cat };
}
`;

if (process.argv.includes("--check")) {
  const cur = fs.existsSync(out) ? fs.readFileSync(out, "utf8") : "";
  if (cur !== body) { console.error("test-ui/program-errors.js is stale: run node test-ui/tests/gen-program-errors.mjs"); process.exit(1); }
  console.log(`program-errors.js up to date (${errs.length} errors)`);
} else {
  fs.writeFileSync(out, body);
  const byCat = {};
  for (const e of errs) byCat[e.cat] = (byCat[e.cat] || 0) + 1;
  console.log(`wrote ${out}: ${errs.length} errors`, byCat);
}
